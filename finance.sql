-- ==============================================================================
-- Table: finance
-- Description: Stores personal transactions for income, expenses, and loans.
-- ==============================================================================

create table if not exists public.finance (
    id bigint generated by default as identity primary key,
    date date not null default current_date,
    amount numeric(12, 2) not null check (amount > 0),
    flow text not null check (flow in ('Credit', 'Debit')),
    type text not null check (type in ('Income', 'Expense', 'Loan')),
    category text not null check (category in ('Needs', 'Wants', 'Savings')),
    method text not null check (method in ('Cash', 'UPI', 'Bank Transfer')),
    note text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- Indexes for Performance
-- Creating an index on 'date' accelerates monthly queries and date range filters.
-- ==============================================================================

create index if not exists idx_finance_date on public.finance (date desc);

-- ==============================================================================
-- Row Level Security (RLS) & Access Policy
-- Enables RLS and allows your application to insert, read, and delete records.
-- ==============================================================================

alter table public.finance enable row level security;

-- Policy granting access for personal app usage
create policy "Allow all operations for personal finance" 
on public.finance 
for all 
using (true) 
with check (true);
